-- An Admin leaves by atomically stepping down to Member and then ending the
-- membership. The existing membership guard protects unresolved withdrawal
-- approver quorums. The Creator cannot leave or transfer their role.
create or replace function public.akiba_leave_group(p_group_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  actor_id uuid := auth.uid();
  group_row public.akiba_groups%rowtype;
  member_row public.akiba_group_memberships%rowtype;
begin
  if actor_id is null then raise exception 'Authentication is required'; end if;
  select * into group_row from public.akiba_groups where id = p_group_id for update;
  if not found then raise exception 'Group not found'; end if;
  if group_row.status <> 'active' then raise exception 'This group is deactivated'; end if;
  select * into member_row from public.akiba_group_memberships
  where group_id = p_group_id and user_id = actor_id and status = 'active' for update;
  if not found then raise exception 'You are not an active member of this group'; end if;
  if member_row.role = 'group_creator' then
    raise exception 'The Group Creator cannot leave or transfer the Creator role';
  end if;
  if member_row.role = 'group_admin' then
    raise exception 'Step down as Group Admin before leaving the group';
  end if;

  update public.akiba_group_memberships
  set status = 'left', ended_at = now()
  where id = member_row.id;

  insert into public.akiba_group_activity(group_id, actor_id, event_type, summary)
  values (p_group_id, actor_id, 'member_left', 'A group member voluntarily left the group.');
end;
$fn$;
revoke all on function public.akiba_leave_group(uuid) from public, anon;
