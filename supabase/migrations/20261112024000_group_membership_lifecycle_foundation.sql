-- The group creator alone can deactivate a group. The creator identity and
-- membership are permanent; deactivation is not ownership transfer.
create or replace function public.akiba_deactivate_group(p_group_id uuid)
returns timestamptz
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  actor_id uuid := auth.uid();
  group_row public.akiba_groups%rowtype;
  delete_at timestamptz;
begin
  if actor_id is null then raise exception 'Authentication is required'; end if;
  if p_group_id is null then raise exception 'Group is required'; end if;

  select * into group_row
  from public.akiba_groups
  where id = p_group_id
  for update;
  if not found then raise exception 'Group not found'; end if;
  if group_row.created_by <> actor_id then
    raise exception 'Only the Group Creator can deactivate this group';
  end if;
  if group_row.status = 'deactivated' then return group_row.scheduled_delete_at; end if;
  if group_row.status <> 'active' then raise exception 'This group is already deleted'; end if;
  if exists (
    select 1 from public.akiba_withdrawal_requests r
    where r.group_id = p_group_id
      and r.status in ('pending_approval', 'approved', 'processing', 'failed_pending_reconciliation')
  ) then
    raise exception 'Resolve outstanding withdrawals before deactivating the group';
  end if;

  update public.akiba_groups
  set status = 'deactivated', updated_at = clock_timestamp()
  where id = p_group_id
  returning scheduled_delete_at into delete_at;

  update public.akiba_group_invitations
  set status = 'cancelled', updated_at = now()
  where group_id = p_group_id and status = 'pending';

  insert into public.akiba_group_activity(group_id, actor_id, event_type, summary)
  values (p_group_id, actor_id, 'group_deactivated',
    'The Group Creator deactivated this group. It is scheduled for deletion after the six-month retention period.');
  return delete_at;
end;
$fn$;
revoke all on function public.akiba_deactivate_group(uuid) from public, anon;
grant execute on function public.akiba_deactivate_group(uuid) to authenticated;

-- Every active member can invite. Capacity is checked at invitation creation
-- and again atomically at acceptance; pending invitations do not reserve slots.
create or replace function public.akiba_create_group_invitation(
  p_group_id uuid,
  p_token_hash text,
  p_expires_at timestamptz,
  p_recipient_email text default null,
  p_recipient_username text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  actor_id uuid := auth.uid();
  group_row public.akiba_groups%rowtype;
  plan_row public.akiba_group_plan_entitlements%rowtype;
  target_user_id uuid;
  target_email text;
  normalized_email text := nullif(lower(btrim(coalesce(p_recipient_email, ''))), '');
  normalized_username text := nullif(lower(btrim(coalesce(p_recipient_username, ''))), '');
  recipient_key_value text;
  invitation_id uuid;
  active_count integer;
begin
  if actor_id is null then raise exception 'Authentication is required'; end if;
  if p_group_id is null or p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$'
     or p_expires_at is null or p_expires_at <= now()
     or p_expires_at > now() + interval '30 days'
     or (normalized_email is not null and normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$')
     or (normalized_username is not null and normalized_username !~ '^[a-z][a-z0-9_]{2,19}$')
     or (normalized_email is not null and normalized_username is not null) then
    raise exception 'Invalid invitation details';
  end if;

  select * into group_row from public.akiba_groups where id = p_group_id for update;
  if not found then raise exception 'Group not found'; end if;
  if group_row.status <> 'active' then raise exception 'This group is deactivated and cannot accept invitations'; end if;
  if not exists (
    select 1 from public.akiba_group_memberships
    where group_id = p_group_id and user_id = actor_id and status = 'active'
  ) then raise exception 'Only active group members can invite people'; end if;

  select * into plan_row from public.akiba_group_plan_entitlements
  where plan_code = group_row.group_plan_code and is_active = true;
  if not found then raise exception 'The group plan is unavailable'; end if;

  select count(*) into active_count from public.akiba_group_memberships
  where group_id = p_group_id and status = 'active';
  if active_count >= plan_row.max_members then raise exception 'Group capacity reached'; end if;

  if normalized_username is not null then
    select user_id into target_user_id from public.akiba_profiles
    where username = normalized_username;
    if target_user_id is null then raise exception 'No Akiba account was found for that username'; end if;
  elsif normalized_email is not null then
    select id into target_user_id from auth.users
    where lower(email) = normalized_email
    limit 1;
  end if;

  if target_user_id is not null then
    select lower(email) into target_email from auth.users where id = target_user_id;
    if exists (
      select 1 from public.akiba_group_invitations
      where group_id = p_group_id and status = 'pending'
        and (
          intended_user_id = target_user_id
          or (target_email is not null and recipient_email = target_email)
        )
    ) then
      raise exception 'A pending invitation already exists for this person';
    end if;
    if exists (select 1 from public.akiba_group_blocks where group_id = p_group_id and user_id = target_user_id) then
      raise exception 'This person is blocked from joining the group';
    end if;
    if exists (select 1 from public.akiba_group_memberships
      where group_id = p_group_id and user_id = target_user_id and status = 'active') then
      raise exception 'This person is already a group member';
    end if;
  end if;

  recipient_key_value := case
    when target_user_id is not null then 'user:' || target_user_id::text
    when normalized_email is not null then 'email:' || normalized_email
    else 'link:' || gen_random_uuid()::text
  end;

  insert into public.akiba_group_invitations
    (group_id, inviter_id, intended_user_id, recipient_email, recipient_username,
     recipient_key, token_hash, expires_at)
  values
    (p_group_id, actor_id, target_user_id, normalized_email, normalized_username,
     recipient_key_value, p_token_hash, p_expires_at)
  returning id into invitation_id;
  return invitation_id;
end;
$fn$;
revoke all on function public.akiba_create_group_invitation(uuid, text, timestamptz, text, text) from public, anon;
grant execute on function public.akiba_create_group_invitation(uuid, text, timestamptz, text, text) to authenticated;

-- Acceptance binds the token to the signed-in account, locks the group before
-- changing membership, and safely reactivates a previous non-active membership.
create or replace function public.akiba_accept_group_invitation(p_token_hash text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  actor_id uuid := auth.uid();
  invitation_group_id uuid;
  group_row public.akiba_groups%rowtype;
  invitation_row public.akiba_group_invitations%rowtype;
  plan_row public.akiba_group_plan_entitlements%rowtype;
  actor_email text;
  active_count integer;
begin
  if actor_id is null then raise exception 'Authentication is required'; end if;
  if p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid invitation'; end if;

  select group_id into invitation_group_id from public.akiba_group_invitations
  where token_hash = p_token_hash;
  if not found then raise exception 'Invitation not found'; end if;

  select * into group_row from public.akiba_groups
  where id = invitation_group_id for update;
  if not found or group_row.status <> 'active' then raise exception 'This group is no longer accepting members'; end if;

  select * into invitation_row from public.akiba_group_invitations
  where token_hash = p_token_hash and group_id = invitation_group_id
  for update;
  if not found then raise exception 'Invitation not found'; end if;
  if invitation_row.status <> 'pending' then raise exception 'This invitation is no longer available'; end if;
  if invitation_row.expires_at <= now() then
    update public.akiba_group_invitations set status = 'expired', updated_at = now()
    where id = invitation_row.id;
    return null;
  end if;

  select lower(email) into actor_email from auth.users where id = actor_id;
  if invitation_row.intended_user_id is not null and invitation_row.intended_user_id <> actor_id then
    raise exception 'This invitation was sent to another Akiba account';
  end if;
  if invitation_row.recipient_email is not null and actor_email is distinct from invitation_row.recipient_email then
    raise exception 'Sign in with the email address this invitation was sent to';
  end if;
  if exists (select 1 from public.akiba_group_blocks where group_id = invitation_group_id and user_id = actor_id) then
    raise exception 'You are blocked from joining this group';
  end if;

  select * into plan_row from public.akiba_group_plan_entitlements
  where plan_code = group_row.group_plan_code and is_active = true;
  if not found then raise exception 'The group plan is unavailable'; end if;
  select count(*) into active_count from public.akiba_group_memberships
  where group_id = invitation_group_id and status = 'active';
  if active_count >= plan_row.max_members then raise exception 'Group capacity reached'; end if;

  if exists (select 1 from public.akiba_group_memberships
    where group_id = invitation_group_id and user_id = actor_id and status = 'active') then
    update public.akiba_group_invitations
      set status = 'accepted', accepted_by = actor_id, accepted_at = now(), updated_at = now()
    where id = invitation_row.id;
    return invitation_group_id;
  end if;

  insert into public.akiba_group_memberships(group_id, user_id, role, status, joined_at, ended_at)
  values (invitation_group_id, actor_id, 'member', 'active', now(), null)
  on conflict (group_id, user_id) do update
    set role = 'member', status = 'active', joined_at = now(), ended_at = null;

  update public.akiba_group_invitations
    set status = 'accepted', accepted_by = actor_id, accepted_at = now(), updated_at = now()
  where id = invitation_row.id;

  insert into public.akiba_group_activity(group_id, actor_id, event_type, summary)
  values (invitation_group_id, actor_id, 'member_joined', 'A person joined the group using an invitation.');
  return invitation_group_id;
end;
$fn$;
revoke all on function public.akiba_accept_group_invitation(text) from public, anon;
grant execute on function public.akiba_accept_group_invitation(text) to authenticated;

create or replace function public.akiba_decline_group_invitation(p_token_hash text)
returns void
