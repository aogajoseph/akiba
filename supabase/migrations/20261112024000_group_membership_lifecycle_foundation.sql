create or replace function public.akiba_remove_group_member(
  p_group_id uuid,
  p_user_id uuid,
  p_block boolean default false
)
returns void
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  actor_id uuid := auth.uid();
  group_row public.akiba_groups%rowtype;
  member_row public.akiba_group_memberships%rowtype;
begin
  if actor_id is null then raise exception 'Authentication is required'; end if;
  select * into group_row from public.akiba_groups where id = p_group_id for update;
  if not found then raise exception 'Group not found'; end if;
  if group_row.status <> 'active' then raise exception 'This group is deactivated'; end if;
  if group_row.created_by <> actor_id then raise exception 'Only the Group Creator can remove or block members'; end if;
  if p_user_id = group_row.created_by then raise exception 'The Group Creator cannot be removed or blocked'; end if;

  select * into member_row from public.akiba_group_memberships
  where group_id = p_group_id and user_id = p_user_id and status = 'active' for update;
  if not found then raise exception 'The selected person is not an active group member'; end if;

  update public.akiba_group_memberships
  set status = 'removed', ended_at = now()
  where id = member_row.id;

  if p_block then
    insert into public.akiba_group_blocks(group_id, user_id, created_by)
    values (p_group_id, p_user_id, actor_id)
    on conflict (group_id, user_id) do nothing;

    update public.akiba_group_invitations
    set status = 'cancelled', updated_at = now()
    where group_id = p_group_id and status = 'pending'
      and (
        intended_user_id = p_user_id
        or recipient_email = (select lower(email) from auth.users where id = p_user_id)
        or recipient_username = (select username from public.akiba_profiles where user_id = p_user_id)
      );
  end if;

  insert into public.akiba_group_activity(group_id, actor_id, event_type, summary)
  values (p_group_id, actor_id,
    case when p_block then 'member_blocked' else 'member_removed' end,
    case when p_block then 'The Group Creator blocked a member from rejoining.'
      else 'The Group Creator removed a member from the group.' end);
end;
$fn$;
revoke all on function public.akiba_remove_group_member(uuid, uuid, boolean) from public, anon;
grant execute on function public.akiba_remove_group_member(uuid, uuid, boolean) to authenticated;

