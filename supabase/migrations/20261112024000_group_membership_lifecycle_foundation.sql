-- All membership mutations stop once a group is deactivated.
create or replace function akiba_private.guard_active_group_membership()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  target_group_id uuid;
  group_status text;
begin
  if current_setting('akiba.system_group_purge', true) = 'on' then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;
  target_group_id := case when tg_op = 'DELETE' then old.group_id else new.group_id end;
  select status into group_status
  from public.akiba_groups
  where id = target_group_id
  for update;
  if not found then raise exception 'Group not found'; end if;
  if group_status <> 'active' then
    raise exception 'This group is deactivated and no longer accepts membership changes';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$fn$;
revoke all on function akiba_private.guard_active_group_membership() from public, anon, authenticated;
drop trigger if exists akiba_group_active_membership_guard on public.akiba_group_memberships;
create trigger akiba_group_active_membership_guard
before insert or update or delete on public.akiba_group_memberships
for each row execute function akiba_private.guard_active_group_membership();

