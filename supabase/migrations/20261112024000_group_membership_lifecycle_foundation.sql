-- Invitation tokens are generated by the application and only their SHA-256
-- digest is stored here. A pending invitation never reserves member capacity.
create table if not exists public.akiba_group_invitations (
  id uuid primary key default gen_random_uuid(),
  group_id uuid not null references public.akiba_groups(id) on delete restrict,
  inviter_id uuid not null references auth.users(id) on delete restrict,
  intended_user_id uuid references auth.users(id) on delete restrict,
  recipient_email text,
  recipient_username text,
  recipient_key text not null,
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  status text not null default 'pending'
    check (status in ('pending', 'accepted', 'declined', 'cancelled', 'expired')),
  expires_at timestamptz not null,
  accepted_by uuid references auth.users(id) on delete restrict,
  accepted_at timestamptz,
  declined_by uuid references auth.users(id) on delete restrict,
  declined_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (recipient_email is null or (
    recipient_email = lower(btrim(recipient_email))
    and recipient_email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  )),
  check (recipient_username is null or recipient_username ~ '^[a-z][a-z0-9_]{2,19}$'),
  check (not (recipient_email is not null and recipient_username is not null)),
  check ((status = 'accepted') = (accepted_by is not null and accepted_at is not null)),
  check ((status = 'declined') = (declined_by is not null and declined_at is not null))
);
create unique index if not exists akiba_group_invitations_pending_recipient_idx
  on public.akiba_group_invitations(group_id, recipient_key)
  where status = 'pending';
create unique index if not exists akiba_group_invitations_pending_email_idx
  on public.akiba_group_invitations(group_id, lower(recipient_email))
  where status = 'pending' and recipient_email is not null;
create unique index if not exists akiba_group_invitations_pending_user_idx
  on public.akiba_group_invitations(group_id, intended_user_id)
  where status = 'pending' and intended_user_id is not null;
create index if not exists akiba_group_invitations_group_status_idx
  on public.akiba_group_invitations(group_id, status, created_at desc);
create index if not exists akiba_group_invitations_expiry_idx
  on public.akiba_group_invitations(expires_at)
  where status = 'pending';

